#!/usr/bin/env bash
#
# Fetches the LiteRT-LM Swift package for the iOS app into iosApp/Vendor/LiteRTLM.
#
# Why not a plain Swift Package Manager dependency: SwiftPM clones the whole LiteRT-LM repository
# (hundreds of MB of history) and downloads the 120 MB binary framework over one connection. On a
# slow link that takes hours. This script does a sparse shallow clone of only the Swift sources at
# the pinned tag and downloads the release binary over several connections, then checks the
# SHA-256 against the checksum the upstream Package.swift publishes. The result is a local Swift
# package with the same sources and the same binary framework, pinned to the same version as
# the Android build (gradle/libs.versions.toml: litertlm).
#
# Usage: scripts/ios_fetch_litertlm.sh            (idempotent; re-run after a version bump)
# Needs: git, curl, unzip, shasum.

set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="$(grep -E '^litertlm = ' gradle/libs.versions.toml | sed -E 's/.*"(.*)".*/\1/')"
TAG="v${VERSION}"
REPO="https://github.com/google-ai-edge/LiteRT-LM"
DEST="iosApp/Vendor/LiteRTLM"
CONNECTIONS=8

if [ -f "$DEST/.version" ] && [ "$(cat "$DEST/.version")" = "$VERSION" ]; then
    echo "LiteRT-LM $VERSION already fetched in $DEST"
    exit 0
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "Sparse clone of $REPO at $TAG (Swift sources only)"
git clone -q --depth 1 --branch "$TAG" --filter=blob:none --sparse "$REPO" "$WORK/repo" 2>&1 | grep -v "detached HEAD" || true
git -C "$WORK/repo" sparse-checkout set swift >/dev/null

# The upstream manifest publishes the binary's URL and checksum; trust only those.
MANIFEST="$WORK/repo/Package.swift"
checksum_of() { # <binary target name>
    awk -v n="name: \"$1\"" 'index($0, n) {f=1} f && /checksum:/ {gsub(/[^0-9a-f]/, "", $0); sub(/checksum/, "", $0); print; exit}' "$MANIFEST"
}
EXPECTED="$(grep -A4 'name: "CLiteRTLM",' "$MANIFEST" | grep checksum | sed -E 's/.*"([0-9a-f]{64})".*/\1/')"
[ -n "$EXPECTED" ] || { echo "could not read the iOS checksum from $MANIFEST" >&2; exit 1; }
URL="$REPO/releases/download/$TAG/CLiteRTLM.xcframework.zip"

echo "Downloading CLiteRTLM.xcframework.zip over $CONNECTIONS connections"
FINAL="$(curl -4 -sIL -o /dev/null -w '%{url_effective}' "$URL")"
SIZE="$(curl -4 -sIL "$URL" | awk 'tolower($1)=="content-length:" {v=$2} END {print v+0}' | tr -d '\r')"
[ "$SIZE" -gt 1000000 ] || { echo "unexpected size '$SIZE' for $URL" >&2; exit 1; }
CHUNK=$(( (SIZE + CONNECTIONS - 1) / CONNECTIONS ))
for i in $(seq 0 $((CONNECTIONS - 1))); do
    start=$(( i * CHUNK )); end=$(( start + CHUNK - 1 ))
    [ "$end" -ge "$SIZE" ] && end=$(( SIZE - 1 ))
    ( until curl -4 -sfL --retry 5 -r "$start-$end" -o "$WORK/part$i" "$URL"; do sleep 2; done ) &
done
wait
for i in $(seq 0 $((CONNECTIONS - 1))); do cat "$WORK/part$i"; done > "$WORK/CLiteRTLM.xcframework.zip"

ACTUAL="$(shasum -a 256 "$WORK/CLiteRTLM.xcframework.zip" | awk '{print $1}')"
if [ "$ACTUAL" != "$EXPECTED" ]; then
    echo "checksum mismatch: expected $EXPECTED, got $ACTUAL" >&2
    exit 1
fi

rm -rf "$DEST"
mkdir -p "$DEST/Sources/LiteRTLM" "$DEST/Frameworks"
unzip -q "$WORK/CLiteRTLM.xcframework.zip" -d "$DEST/Frameworks"
for f in "$WORK"/repo/swift/*.swift; do
    case "$(basename "$f")" in *Tests.swift) continue ;; esac
    cp "$f" "$DEST/Sources/LiteRTLM/"
done
[ -f "$WORK/repo/LICENSE" ] && cp "$WORK/repo/LICENSE" "$DEST/LICENSE"

cat > "$DEST/Package.swift" <<'SWIFT'
// swift-tools-version: 5.9
// Generated by scripts/ios_fetch_litertlm.sh: the upstream LiteRT-LM Swift sources and the
// checksum-verified binary framework of the pinned release, as a local package.
import PackageDescription

let package = Package(
    name: "LiteRTLM",
    platforms: [.iOS(.v15)],
    products: [.library(name: "LiteRTLM", targets: ["LiteRTLM"])],
    targets: [
        .binaryTarget(name: "CLiteRTLM", path: "Frameworks/CLiteRTLM.xcframework"),
        .target(name: "LiteRTLM", dependencies: ["CLiteRTLM"], path: "Sources/LiteRTLM"),
    ]
)
SWIFT
echo "$VERSION" > "$DEST/.version"
echo "LiteRT-LM $VERSION ready in $DEST (checksum $ACTUAL)"
